/** Import / export of configuration files and generated artefacts. */
import type { PraveshConfig } from '../config/types';
import { validateConfig, type ValidationResult } from './validation';

export function serializeConfig(config: PraveshConfig): string {
  return `${JSON.stringify(config, null, 2)}\n`;
}

export function configFileName(config: PraveshConfig): string {
  return `${config.id || 'pravesh'}.config.json`;
}

export function downloadText(filename: string, text: string, mime = 'application/json') {
  const blob = new Blob([text], { type: `${mime};charset=utf-8` });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  a.remove();
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}

export async function copyText(text: string): Promise<boolean> {
  try {
    await navigator.clipboard.writeText(text);
    return true;
  } catch {
    // Fallback for non-secure contexts.
    const ta = document.createElement('textarea');
    ta.value = text;
    ta.setAttribute('readonly', '');
    ta.style.position = 'fixed';
    ta.style.opacity = '0';
    document.body.appendChild(ta);
    ta.select();
    let ok = false;
    try {
      ok = document.execCommand('copy');
    } catch {
      ok = false;
    }
    ta.remove();
    return ok;
  }
}

export interface ImportOutcome {
  config: PraveshConfig | null;
  result: ValidationResult;
  parseError?: string;
}

export function parseConfigText(text: string): ImportOutcome {
  let parsed: unknown;
  try {
    parsed = JSON.parse(text);
  } catch (e) {
    const message = e instanceof Error ? e.message : 'Invalid JSON';
    return {
      config: null,
      parseError: message,
      result: { valid: false, errors: [{ level: 'error', path: 'file', message: `is not valid JSON (${message})` }], warnings: [] },
    };
  }
  const result = validateConfig(parsed);
  return { config: result.valid ? (parsed as PraveshConfig) : null, result };
}

export async function readConfigFile(file: File): Promise<ImportOutcome> {
  if (file.size > 5 * 1024 * 1024) {
    return {
      config: null,
      result: { valid: false, errors: [{ level: 'error', path: 'file', message: 'is larger than 5 MB' }], warnings: [] },
    };
  }
  return parseConfigText(await file.text());
}

/**
 * Builds a `.env.example` from declared variables. Secret variables are
 * always emitted with an empty value; only non-secret examples are filled.
 */
export function generateEnvExample(config: PraveshConfig): string {
  const lines: string[] = [
    `# ${config.identity.name}, environment variables`,
    `# Generated by Pravesh from ${configFileName(config)}`,
    '#',
    '# VITE_* variables are bundled into the browser build and must never hold secrets.',
    '# All other variables are read by your backend / API gateway only.',
    '',
  ];
  const pub = config.technical.envVars.filter((e) => !e.secret);
  const sec = config.technical.envVars.filter((e) => e.secret);
  const emit = (e: (typeof pub)[number]) => {
    lines.push(`# ${e.description || e.name}${e.required ? ' (required)' : ' (optional)'}`);
    lines.push(`${e.name}=${e.secret ? '' : e.example}`);
    lines.push('');
  };
  if (pub.length) {
    lines.push('# --- Public configuration ---------------------------------------', '');
    pub.forEach(emit);
  }
  if (sec.length) {
    lines.push('# --- Server-side secrets (never commit real values) -------------', '');
    sec.forEach(emit);
  }
  return lines.join('\n');
}
